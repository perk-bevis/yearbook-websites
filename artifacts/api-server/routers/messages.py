import uuid

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel
from typing import Optional
from fastapi.responses import RedirectResponse
from database import get_db, row_to_dict, rows_to_list
from auth import require_user
from object_storage import create_upload, signed_object_url

router = APIRouter(tags=["messages"])


class SendMessageRequest(BaseModel):
    receiver_id: str
    content: str


class AttachmentUploadRequest(BaseModel):
    kind: str
    content_type: str
    size: int


@router.post("/messages/attachments/request-url")
def request_message_attachment(body: AttachmentUploadRequest, user_id: str = Depends(require_user)):
    content_type = body.content_type.split(";", 1)[0].strip().lower()
    image_types = {"image/jpeg", "image/png", "image/webp", "image/gif"}
    audio_types = {
        "audio/webm", "audio/ogg", "audio/mp4", "audio/mpeg",
        "audio/wav", "audio/aac", "audio/x-m4a", "audio/3gpp",
    }
    file_types = {
        "application/pdf", "text/plain",
        "application/msword",
        "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    }
    allowed_types = {
        "image": image_types,
        "audio": audio_types,
        "file": file_types,
    }
    if body.kind not in allowed_types or content_type not in allowed_types[body.kind]:
        raise HTTPException(status_code=415, detail="Định dạng tệp đính kèm chưa được hỗ trợ")
    max_size = 12 * 1024 * 1024 if body.kind == "image" else 25 * 1024 * 1024
    if body.size <= 0 or body.size > max_size:
        message = "Ảnh không được vượt quá 12 MB" if body.kind == "image" else "Tệp không được vượt quá 25 MB"
        raise HTTPException(status_code=413, detail=message)

    upload_url, object_path = create_upload()
    object_name = object_path.removeprefix("/api/storage/objects/")
    return {"uploadURL": upload_url, "objectName": object_name}


@router.get("/messages/attachments/{object_name:path}")
def serve_message_attachment(object_name: str, user_id: str = Depends(require_user)):
    # Upload names are UUIDs generated by this server; reject arbitrary object paths.
    try:
        prefix, object_id = object_name.split("/", 1)
        if prefix != "uploads":
            raise ValueError("invalid attachment path")
        uuid.UUID(object_id)
    except (ValueError, AttributeError):
        raise HTTPException(status_code=404, detail="Không tìm thấy tệp đính kèm")

    attachment_ref = f"/api/messages/attachments/{object_name}"
    with get_db() as conn:
        cur = conn.cursor()
        cur.execute(
            """
            SELECT 1 FROM direct_messages
            WHERE (sender_id = %s OR receiver_id = %s)
              AND content LIKE %s
            LIMIT 1
            """,
            (user_id, user_id, f"%{attachment_ref}%"),
        )
        allowed = cur.fetchone() is not None
        if not allowed:
            cur.execute(
                """
                SELECT 1
                FROM group_messages gm
                JOIN group_members mine ON mine.group_id = gm.group_id
                WHERE mine.user_id = %s AND gm.content LIKE %s
                LIMIT 1
                """,
                (user_id, f"%{attachment_ref}%"),
            )
            allowed = cur.fetchone() is not None

    if not allowed:
        raise HTTPException(status_code=404, detail="Không tìm thấy tệp đính kèm")
    return RedirectResponse(signed_object_url("GET", object_name, ttl_seconds=300))


@router.post("/messages/send", status_code=201)
def send_message(body: SendMessageRequest, sender_id: str = Depends(require_user)):
    if not body.content.strip():
        raise HTTPException(status_code=400, detail="Tin nhắn không được trống")
    if body.receiver_id == sender_id:
        raise HTTPException(status_code=400, detail="Không thể nhắn tin cho chính mình")
    with get_db() as conn:
        cur = conn.cursor()
        cur.execute(
            "INSERT INTO direct_messages (sender_id, receiver_id, content) VALUES (%s, %s, %s) RETURNING *",
            (sender_id, body.receiver_id, body.content.strip()),
        )
        return row_to_dict(cur, cur.fetchone())


@router.get("/messages/conversations")
def list_conversations(user_id: str = Depends(require_user)):
    """Return list of unique conversation partners with last message + unread count."""
    with get_db() as conn:
        cur = conn.cursor()
        cur.execute("""
            WITH partners AS (
                SELECT DISTINCT
                    CASE WHEN sender_id = %s THEN receiver_id ELSE sender_id END AS partner_id
                FROM direct_messages
                WHERE sender_id = %s OR receiver_id = %s
            ),
            last_msgs AS (
                SELECT
                    p.partner_id,
                    (SELECT CASE
                         WHEN content LIKE 'YB_ATTACHMENT:%%' AND content LIKE '%%"type":"audio"%%' THEN 'Tin nhắn thoại'
                         WHEN content LIKE 'YB_ATTACHMENT:%%' AND content LIKE '%%"type":"image"%%' THEN 'Đã gửi ảnh'
                         WHEN content LIKE 'YB_ATTACHMENT:%%' THEN 'Đã gửi tệp'
                         ELSE content
                     END FROM direct_messages
                     WHERE (sender_id = %s AND receiver_id = p.partner_id)
                        OR (sender_id = p.partner_id AND receiver_id = %s)
                     ORDER BY created_at DESC LIMIT 1) AS last_message,
                    (SELECT created_at FROM direct_messages
                     WHERE (sender_id = %s AND receiver_id = p.partner_id)
                        OR (sender_id = p.partner_id AND receiver_id = %s)
                     ORDER BY created_at DESC LIMIT 1) AS last_at,
                    (SELECT COUNT(*) FROM direct_messages
                     WHERE sender_id = p.partner_id AND receiver_id = %s AND is_read = FALSE
                    ) AS unread_count
                FROM partners p
            )
            SELECT
                lm.partner_id,
                lm.last_message,
                lm.last_at,
                lm.unread_count,
                au.full_name,
                au.nickname,
                au.photo_url,
                   au.role,
                   au.last_seen_at,
                   (au.last_seen_at IS NOT NULL AND au.last_seen_at > NOW() - INTERVAL '2 minutes') AS online
            FROM last_msgs lm
            LEFT JOIN app_users au ON au.clerk_user_id = lm.partner_id
            ORDER BY lm.last_at DESC
        """, (user_id, user_id, user_id, user_id, user_id, user_id, user_id, user_id))
        return rows_to_list(cur, cur.fetchall())


@router.get("/messages/thread/{other_user_id}")
def get_thread(other_user_id: str, user_id: str = Depends(require_user)):
    with get_db() as conn:
        cur = conn.cursor()
        # Mark messages from other_user_id to user_id as read
        cur.execute(
            "UPDATE direct_messages SET is_read = TRUE WHERE sender_id = %s AND receiver_id = %s",
            (other_user_id, user_id),
        )
        cur.execute("""
            SELECT dm.*, 
                   au.full_name, au.nickname, au.photo_url
            FROM direct_messages dm
            LEFT JOIN app_users au ON au.clerk_user_id = dm.sender_id
            WHERE (dm.sender_id = %s AND dm.receiver_id = %s)
               OR (dm.sender_id = %s AND dm.receiver_id = %s)
            ORDER BY dm.created_at ASC
        """, (user_id, other_user_id, other_user_id, user_id))
        return rows_to_list(cur, cur.fetchall())


@router.get("/messages/unread-count")
def unread_count(user_id: str = Depends(require_user)):
    with get_db() as conn:
        cur = conn.cursor()
        cur.execute(
            "SELECT COUNT(*) as count FROM direct_messages WHERE receiver_id = %s AND is_read = FALSE",
            (user_id,),
        )
        row = cur.fetchone()
        return {"count": row[0] if row else 0}


@router.get("/users/list")
def list_users(user_id: str = Depends(require_user)):
    """Return all users except the current one (for starting new conversations)."""
    with get_db() as conn:
        cur = conn.cursor()
        cur.execute("""
            SELECT clerk_user_id, full_name, nickname, photo_url, role, last_seen_at,
                   (last_seen_at IS NOT NULL AND last_seen_at > NOW() - INTERVAL '2 minutes') AS online
            FROM app_users
            WHERE clerk_user_id != %s
            ORDER BY full_name ASC
        """, (user_id,))
        return rows_to_list(cur, cur.fetchall())
